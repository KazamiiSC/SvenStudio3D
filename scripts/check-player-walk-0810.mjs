/** Deterministic no-browser physics + integration regression for Player Walk. */
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import ts from 'typescript';
const root=path.resolve(import.meta.dirname,'..');
const source=fs.readFileSync(path.join(root,'src/engine/playerWalk.ts'),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const m=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const collider=(min,max)=>({min,max});
const floor=collider([-100,-12,-100],[100,0,100]);
const wall=collider([40,0,-30],[55,160,30]);
const roof=collider([-100,90,-100],[100,108,100]);
const bounds=[floor,wall,roof];
const input={forward:0,strafe:0,yaw:Math.PI/2,run:false,crouch:false,jump:false};
const ticks=(state,controls,world,count)=>{for(let n=0;n<count;n++)state=m.walkStep(state,controls,world,1/60);return state};
let pose=m.chooseWalkStart([0,40,0],bounds);
assert(Math.abs(pose.position[1])<.1&&pose.grounded,'Player must land at info_player_start near floor');
pose=ticks(pose,{...input,forward:1},bounds,120);
assert(pose.position[0]>20&&pose.position[0]<25,`Must stop at wall, x=${pose.position[0]}`);
pose=ticks(pose,{...input,forward:1,strafe:1},bounds,90);
assert(pose.position[2]>10,'Must slide along wall rather than freeze');
pose=m.chooseWalkStart([0,40,0],[floor]);
pose=ticks(pose,{...input,jump:true},[floor],1);
assert(pose.velocityY>0&&!pose.grounded,'Jump impulse should leave ground');
const peak=ticks(pose,input,[floor],20);
assert(peak.position[1]>25,'Jump needs actual height');
pose=ticks(pose,input,[floor],120);
assert(pose.grounded&&Math.abs(pose.position[1])<.1,'Gravity must land on floor');
const corridor=[floor,collider([-30,39,-30],[30,80,30])];
const standing=m.chooseWalkStart([0,40,0],[floor]);
assert(m.walkIntersects(standing.position,m.WALK.standHeight,corridor[1]),'Standing body collides with ceiling');
assert(!m.walkIntersects(standing.position,m.WALK.crouchHeight,corridor[1]),'Crouched body fits low tunnel');
let crouched=m.walkStep({...standing,crouched:true},{...input,crouch:false},corridor,1/60);
assert(crouched.crouched,'Releasing Ctrl cannot force player upright under low ceiling');
const step=collider([25,0,-30],[48,15,30]);
pose=m.chooseWalkStart([0,40,0],[floor,step]);
pose=ticks(pose,{...input,forward:1},[floor,step],15);
assert(pose.position[1]>14,'Must climb short step');
assert(Math.abs(m.chooseWalkStart([5,40,0],[floor]).position[0]-5)<.01,'Spawn x retained');
assert(m.walkCollider([[0,0,0],[2,0,0],[2,2,0],[0,0,3]]),'Build bounds from vertices');
assert.equal(m.walkCollider([[0,0,0],[1,0,0]]),null,'Reject invalid collider');
const view=fs.readFileSync(path.join(root,'src/components/Viewport.tsx'),'utf8');
const app=fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
const store=fs.readFileSync(path.join(root,'src/store.ts'),'utf8');
for(const name of ['Player Walk Mode','walkColliders','chooseWalkStart','walkStep','walkMode','requestPointerLock'])assert(view.includes(name),`Missing ${name}`);
for(const name of ['setWalk','walkMode','Escape','ShiftLeft'])assert(view.includes(name)||app.includes(name),`Missing ${name}`);
assert(store.includes('walkMode:false')&&store.includes('toggleWalk'),'Walk state must be separate from Fly');
for(const lang of ['es','ru','ko'])assert(fs.readFileSync(path.join(root,'src/i18n.ts'),'utf8').includes('Player Walk Mode'));
console.log('PASS Player Walk Mode: 15 physics/UI/state checks, spawn, wall slide, gravity, jump, crouch, step, input and map preservation.');
