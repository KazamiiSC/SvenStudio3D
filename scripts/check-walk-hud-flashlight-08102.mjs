import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';

const source=readFileSync('src/engine/previewEnhancements.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
new Function('module','exports',js)(module,module.exports);
const {normalizeWalkPreview,DEFAULT_WALK_PREVIEW}=module.exports;
assert.equal(DEFAULT_WALK_PREVIEW.showHud,true,'HUD should be on for new installations');
assert.equal(normalizeWalkPreview(null).showHud,true);
assert.equal(normalizeWalkPreview({showHud:false}).showHud,false,'manual preference must persist');
assert.equal(normalizeWalkPreview(null).flashlightPower,60000);
assert.equal(normalizeWalkPreview({flashlightPower:0}).flashlightPower,10000);
assert.equal(normalizeWalkPreview({flashlightPower:999999}).flashlightPower,120000);
assert.equal(normalizeWalkPreview({flashlightPower:45000}).flashlightPower,45000);
const viewport=readFileSync('src/components/Viewport.tsx','utf8');
const styles=readFileSync('src/style.css','utf8');
const translations=readFileSync('src/i18n.ts','utf8');
assert(viewport.includes("new THREE.SpotLight('#fff7e4',60000"),'flashlight should use visible physically correct power');
assert(viewport.includes('spot.intensity=walk.flashlightPower'),'light power should update live');
assert(viewport.includes("e.code==='KeyF'"),'F key should toggle flashlight');
assert(viewport.includes("e.code==='KeyH'"),'H key should toggle HUD');
assert(viewport.includes("showHud:!walkSettingsRef.current.showHud"),'H must flip HUD state');
assert(viewport.includes('player-walk-mode-status'),'HUD status must remain visible even when HUD is hidden');
assert(viewport.includes("<span>XYZ: {walkStats.position.map"),'HUD must include coordinates');
assert(styles.includes('.viewport-frame .player-walk-info{left:auto;right:15px;top:14px'),'player HUD should avoid Walk toolbar');
for(const term of ["'Flashlight power':'Potencia de linterna'","'Flashlight power':'Мощность фонарика'","'Flashlight power':'손전등 밝기'"])
 assert(translations.includes(term),`missing translation ${term}`);
console.log('PASS v0.8.10.2: flashlight strength, F/H keys, persistent Walk HUD, readable position and four-language support');
