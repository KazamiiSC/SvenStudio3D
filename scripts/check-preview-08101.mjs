import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=readFileSync('src/engine/previewEnhancements.ts','utf8');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
new Function('module','exports',js)(module,module.exports);
const m=module.exports;
assert.equal(m.goldSrcMaterial('{glass').kind,'masked');
assert.equal(m.goldSrcMaterial('!water1').kind,'water');
assert.equal(m.goldSrcMaterial('*water1').kind,'water');
assert.equal(m.goldSrcMaterial('big_glass_window').kind,'glass');
assert.equal(m.goldSrcMaterial('BRICK01').kind,'opaque');
assert.equal(m.goldSrcMaterial('BRICK01',{props:{rendermode:'5',renderamt:'128'}}).kind,'additive');
assert(m.goldSrcMaterial('!water').opacity<1);
assert.equal(m.normalizeWalkPreview({walkSpeed:10000}).walkSpeed,600);
assert.equal(m.normalizeGoldSrcPreview({exposure:20}).exposure,2);
assert.equal(m.normalizeWalkPreview({showHud:false}).showHud,false);
assert(Math.abs(m.noclipDisplacement(0,0,1,0,0,100,1/10)[2]+10)<.01);
assert(Math.abs(m.noclipDisplacement(0,0,0,0,1,100,1/10)[1]-10)<.01);
console.log('PASS: GoldSrc material types, render modes, settings ranges and noclip motion');
